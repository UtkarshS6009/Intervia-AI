import os
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors

class ReportService:
    def __init__(self):
        self.reports_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../../reports"))
        os.makedirs(self.reports_dir, exist_ok=True)

    def generate_pdf_report(self, session_data: dict, file_name: str) -> str:
        """Generates a professional PDF performance report."""
        file_path = os.path.join(self.reports_dir, file_name)
        c = canvas.Canvas(file_path, pagesize=letter)
        width, height = letter
        
        # Header
        c.setFillColor(colors.HexColor("#0f172a"))
        c.rect(0, height - 80, width, 80, stroke=0, fill=1)
        c.setFillColor(colors.white)
        c.setFont("Helvetica-Bold", 24)
        c.drawString(40, height - 45, "AI Interview Coach")
        c.setFont("Helvetica", 12)
        c.setFillColor(colors.HexColor("#94a3b8"))
        c.drawString(40, height - 65, "Official Candidate Performance Assessment")

        # Candidate Info
        c.setFillColor(colors.black)
        c.setFont("Helvetica-Bold", 14)
        c.drawString(40, height - 120, f"Candidate: {session_data.get('candidate_name', 'Alex Mercer')}")
        c.setFont("Helvetica", 12)
        c.drawString(40, height - 140, f"Target Role: {session_data.get('target_role', 'Software Engineer')}")
        c.drawString(40, height - 160, f"Interview Category: {session_data.get('category', 'Technical')}")
        
        # Score
        c.setFont("Helvetica-Bold", 16)
        c.setFillColor(colors.HexColor("#6366f1"))
        c.drawString(400, height - 140, f"Overall Score: {session_data.get('overall_score', 0)}/100")
        
        # Footer
        c.setFont("Helvetica", 10)
        c.setFillColor(colors.gray)
        c.drawString(40, 30, "Generated by AI Interview Coach - Confidential")
        
        c.save()
        return file_path